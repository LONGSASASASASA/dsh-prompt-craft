#!/usr/bin/env node
/**
 * Build the publishable package:
 *  - src/host/*.cjs + src/protocol.cjs -> lib/ (host half, plain CommonJS)
 *  - src/client/index.js -> lib/client.js (single browser bundle wrapped in the
 *    DSH ModuleLoader envelope)
 *
 * Usage:
 *   node scripts/build.mjs            write lib/
 *   node scripts/build.mjs --check    exit 1 when lib/ is out of date
 *   node scripts/build.mjs --minify   minify the client bundle
 */

import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const minify = process.argv.includes('--minify');

/** Modules the DSH web shell provides at runtime (see PLATFORM_MODULES). */
const CLIENT_EXTERNALS = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
];

const CLIENT_ENTRY = join(root, 'src', 'client', 'index.js');
const CLIENT_OUTPUT = 'lib/client.js';

/**
 * @param {string} code esbuild CJS output
 * @returns {string} bundle wrapped in the ModuleLoader factory envelope
 */
function wrapClientBundle(code) {
  const indented = code
    .split('\n')
    .map((line) => (line.length > 0 ? '    ' + line : line))
    .join('\n');
  return [
    '/*! dsh-prompt-craft client bundle — generated by scripts/build.mjs; edit src/client/ instead. */',
    'window.__ModuleLoader__.load({',
    '  id: "dsh-prompt-craft",',
    '  factory: function (require) {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    indented,
    '    return module.exports;',
    '  }',
    '});',
    '',
  ].join('\n');
}

async function bundleClient() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [CLIENT_ENTRY],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['es2020'],
    logLevel: 'silent',
    external: CLIENT_EXTERNALS,
    legalComments: 'none',
    minify,
    charset: 'utf8',
  });
  if (result.outputFiles.length !== 1) {
    throw new Error('expected exactly one esbuild output file');
  }
  return wrapClientBundle(result.outputFiles[0].text);
}

/**
 * @returns {Promise<Map<string, Buffer>>} package-relative path -> bytes
 */
async function collectOutputs() {
  /** @type {Map<string, Buffer>} */
  const outputs = new Map();
  outputs.set('lib/protocol.cjs', await readFile(join(root, 'src', 'protocol.cjs')));

  const hostDir = join(root, 'src', 'host');
  const hostFiles = (await readdir(hostDir)).filter((name) => name.endsWith('.cjs')).sort();
  for (const name of hostFiles) {
    outputs.set('lib/host/' + name, await readFile(join(hostDir, name)));
  }

  outputs.set(CLIENT_OUTPUT, Buffer.from(await bundleClient(), 'utf8'));
  return outputs;
}

async function main() {
  const outputs = await collectOutputs();

  if (checkOnly) {
    const drifted = [];
    for (const [relative, content] of outputs) {
      const target = join(root, relative);
      const existing = existsSync(target) ? await readFile(target) : null;
      if (existing === null || !existing.equals(content)) drifted.push(relative);
    }
    if (drifted.length > 0) {
      console.error('[dsh-prompt-craft] lib/ is out of date; run `npm run build`. Stale:');
      for (const relative of drifted) console.error('  - ' + relative);
      process.exit(1);
    }
    console.log('[dsh-prompt-craft] lib/ is up to date (' + outputs.size + ' files).');
    return;
  }

  await rm(join(root, 'lib'), { recursive: true, force: true });
  for (const [relative, content] of outputs) {
    const target = join(root, relative);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log('  wrote ' + relative + ' (' + content.length + ' bytes)');
  }
  console.log('[dsh-prompt-craft] build complete: ' + outputs.size + ' files.');
}

main().catch((error) => {
  console.error('[dsh-prompt-craft] build failed: ' + (error && error.stack ? error.stack : String(error)));
  process.exit(1);
});
